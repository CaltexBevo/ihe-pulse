export interface InnovationGrantGroups {
  "closing-soon": InnovationGrantOpportunity[];
  "open-now": InnovationGrantOpportunity[];
  "opening-soon": InnovationGrantOpportunity[];
  "recurring-watchlist": InnovationGrantOpportunity[];
  closed: InnovationGrantOpportunity[];
}

export function groupInnovationGrants(asOf: Date = new Date()): InnovationGrantGroups {
  const groups: InnovationGrantGroups = {
    "closing-soon": [],
    "open-now": [],
    "opening-soon": [],
    "recurring-watchlist": [],
    closed: [],
  };

  for (const opportunity of innovationGrants) {
    if (opportunity.scopeDisposition !== "included") continue;
    groups[getInnovationGrantLifecycle(opportunity, asOf)].push(opportunity);
  }

  const byDeadline = (left: InnovationGrantOpportunity, right: InnovationGrantOpportunity) =>
    (left.finalDeadlineDate ?? "9999-12-31").localeCompare(
      right.finalDeadlineDate ?? "9999-12-31",
    );

  groups["closing-soon"].sort(byDeadline);
  groups["open-now"].sort(byDeadline);
  groups["opening-soon"].sort(byDeadline);
  groups["recurring-watchlist"].sort(
    (left, right) => left.recommendationRank - right.recommendationRank,
  );
  groups.closed.sort((left, right) => byDeadline(right, left));
  return groups;
}
