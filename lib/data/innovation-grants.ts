type GrantInput = Omit<
  InnovationGrantOpportunity,
  | "qualifiers"
  | "applicationStatus"
  | "announcementWindow"
  | "inventoryOrigin"
> & {
  qualifiers?: string[];
  applicationStatus?: InnovationGrantApplicationStatus;
  announcementWindow?: string;
  inventoryOrigin?: InnovationGrantInventoryOrigin;
};

function grant(input: GrantInput): InnovationGrantOpportunity {
  const inventoryOrigin = input.inventoryOrigin ?? "bootstrap-search";
  const expectedPortalAddedDates =
    inventoryOrigin === "rolling-inventory"
      ? ["2026-08-29"]
      : inventoryOrigin === "bootstrap-search"
        ? ["2026-08-30"]
        : inventoryOrigin === "recurring-watchlist"
          ? ["2026-08-30", "2026-08-31"]
          : ["2026-08-31", "2026-09-07"];

  if (!expectedPortalAddedDates.includes(input.portalAddedDate)) {
    throw new Error(
      `portalAddedDate must be one of ${expectedPortalAddedDates.join(", ")} for ${inventoryOrigin} Innovation Grants records.`,
    );
  }

  return {
    applicationStatus: "open-now",
    announcementWindow: "Six-month bootstrap",
    qualifiers: [],
    ...input,
    inventoryOrigin,
  };
}

